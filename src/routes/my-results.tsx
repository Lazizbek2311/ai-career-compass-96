function deriveSkillsFromCareer(c: CareerReport["careers"][number]) {
  const out: Record<string, number> = {};
  c.technicalSkills.slice(0, 6).forEach((s, i) => {
    out[s] = 5 + ((i * 13) % 5);
  });
  return out;
}

function SkillsRadar({ skills }: { skills: Record<string, number> }) {
  const entries = Object.entries(skills).slice(0, 8);
  const n = entries.length || 1;
  const cx = 160;
  const cy = 160;
  const R = 120;

  const point = (i: number, scale: number) => {
    const angle = (Math.PI * 2 * i) / n - Math.PI / 2;
    return {
      x: cx + Math.cos(angle) * R * scale,
      y: cy + Math.sin(angle) * R * scale,
    };
  };

  const normalize = (v: number) => {
    // Accept 0-10 or 0-100
    const max = Math.max(10, ...entries.map(([, x]) => x));
    return Math.max(0.05, Math.min(1, v / max));
  };

  const polygon = entries
    .map(([, v], i) => {
      const p = point(i, normalize(v));
      return `${p.x},${p.y}`;
    })
    .join(" ");

  return (
    <div className="grid gap-6 lg:grid-cols-[auto_1fr] items-center">
      <svg width="320" height="320" viewBox="0 0 320 320" className="mx-auto">
        <defs>
          <linearGradient id="radarFill" x1="0" y1="0" x2="1" y2="1">
            <stop offset="0%" stopColor="var(--brand)" stopOpacity="0.6" />
            <stop offset="100%" stopColor="var(--brand)" stopOpacity="0.15" />
          </linearGradient>
        </defs>
        {[0.25, 0.5, 0.75, 1].map((s) => (
          <polygon
            key={s}
            points={entries
              .map((_, i) => {
                const p = point(i, s);
                return `${p.x},${p.y}`;
              })
              .join(" ")}
            fill="none"
            stroke="currentColor"
            className="text-border/60"
            strokeWidth="1"
          />
        ))}
        {entries.map((_, i) => {
          const p = point(i, 1);
          return (
            <line
              key={i}
              x1={cx}
              y1={cy}
              x2={p.x}
              y2={p.y}
              stroke="currentColor"
              className="text-border/40"
              strokeWidth="1"
            />
          );
        })}
        <motion.polygon
          points={polygon}
          fill="url(#radarFill)"
          stroke="var(--brand)"
          strokeWidth="2"
          initial={{ opacity: 0, scale: 0.6 }}
          animate={{ opacity: 1, scale: 1 }}
          transition={{ duration: 0.8 }}
          style={{ transformOrigin: `${cx}px ${cy}px` }}
        />
        {entries.map(([label], i) => {
          const p = point(i, 1.15);
          return (
            <text
              key={label}
              x={p.x}
              y={p.y}
              textAnchor="middle"
              dominantBaseline="middle"
              className="fill-foreground text-[10px] font-medium"
            >
              {label.length > 14 ? label.slice(0, 13) + "…" : label}
            </text>
          );
        })}
      </svg>
      <div className="space-y-2">
        {entries.map(([label, v]) => {
          const pct = Math.round(normalize(v) * 100);
          return (
            <div key={label}>
              <div className="flex items-center justify-between text-xs mb-1">
                <span className="font-medium">{label}</span>
                <span className="text-muted-foreground">{pct}%</span>
              </div>
              <Progress value={pct} className="h-1.5" />
            </div>
          );
        })}
      </div>
    </div>
  );
}

