function RoadmapRow({ label, items }: { label: string; items: string[] }) {
  return (
    <div>
      <div className="text-[10px] uppercase tracking-wider text-muted-foreground mb-1">
        {label}
      </div>
      <div className="flex flex-wrap gap-1.5">
        {items.map((it) => (
          <span
            key={it}
            className="rounded-full glass px-2 py-0.5 text-[10px] font-medium"
          >
            {it}
          </span>
        ))}
      </div>
    </div>
  );
}

function buildSixMonths(c: CareerReport["careers"][number]) {
  const tech = c.technicalSkills;
  const soft = c.softSkills;
  const chunk = (arr: string[], i: number, size = 2) =>
    arr.slice(i * size, i * size + size).length
      ? arr.slice(i * size, i * size + size)
      : [arr[i % Math.max(arr.length, 1)] || "Practice"];

  const phases = c.roadmap.length ? c.roadmap : [];
  const focusFor = (i: number) =>
    phases[Math.min(i, phases.length - 1)]?.focus || "Deliberate practice and small projects";
  const titleFor = (i: number) =>
    phases[Math.min(i, phases.length - 1)]?.phase || `Phase ${i + 1}`;

  return Array.from({ length: 6 }).map((_, i) => ({
    title: titleFor(i),
    skills: chunk(tech, i, 2).concat(chunk(soft, i, 1)),
    tech: chunk(tech, i + 1, 2),
    outcome: focusFor(i),
  }));
}

