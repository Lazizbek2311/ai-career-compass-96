function difficultyFromCareer(c: CareerReport["careers"][number]) {
  const skills = c.technicalSkills.length;
  if (skills >= 6) return { label: "Advanced", level: 3 };
  if (skills >= 4) return { label: "Intermediate", level: 2 };
  return { label: "Beginner", level: 1 };
}

function demandLabel(score: number) {
  if (score >= 90) return { label: "Very High", tone: "bg-emerald-500" };
  if (score >= 80) return { label: "High", tone: "bg-sky-500" };
  if (score >= 70) return { label: "Strong", tone: "bg-amber-500" };
  return { label: "Moderate", tone: "bg-muted-foreground" };
}

