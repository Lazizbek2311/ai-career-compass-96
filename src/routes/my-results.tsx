function buildCourses(c: CareerReport["careers"][number]) {
  const platforms = ["Coursera", "Udemy", "edX", "Pluralsight", "DataCamp", "freeCodeCamp"];
  const difficulties = ["Beginner", "Intermediate", "Advanced"];
  const durations = ["4 weeks", "6 weeks", "8 weeks", "10 weeks", "12 weeks"];
  return c.technicalSkills.slice(0, 6).map((skill, i) => ({
    title: `${skill} for ${c.title}`,
    platform: platforms[i % platforms.length],
    difficulty: difficulties[i % difficulties.length],
    duration: durations[i % durations.length],
    progress: [12, 0, 45, 8, 0, 22][i] ?? 0,
  }));
}

